;; Sampling profile of a snapshot's judge: clojure -M probe/perf_prof.clj <snapshot.edn.gz>
(require '[clojurecraft.simrace :as sr] '[clojure.string :as str])
(def path (first *command-line-args*))
(def done (promise))
(def t0 (System/currentTimeMillis))
(def worker (Thread. (fn [] (try (sr/judge! path) (finally (deliver done true))))))
(.start worker)
(def self (atom {}))
(def tops (atom {}))
(def deep (atom {}))
(def samples (atom 0))
(loop [n 0]
  (when (and (not (realized? done)) (< n 15000))
    (Thread/sleep 20)
    (let [st (.getStackTrace worker)
          all (map str st)
          fs (filter #(str/starts-with? % "clojurecraft") all)]
      (swap! samples inc)
      (when-let [f (first all)] (swap! self update (str/replace f #"\(.*" "") (fnil inc 0)))
      (when-let [f (first fs)] (swap! tops update f (fnil inc 0)))
      (doseq [f (distinct (map #(str/replace % #"\(.*" "") fs))]
        (swap! deep update f (fnil inc 0))))
    (recur (inc n))))
(println "PROF-WALL-MS" (- (System/currentTimeMillis) t0) "SAMPLES" @samples)
(println "PROF-SELF")
(doseq [[k v] (take 15 (sort-by (comp - val) @self))] (println v k))
(println "PROF-TOP")
(doseq [[k v] (take 25 (sort-by (comp - val) @tops))] (println v k))
(println "PROF-INCLUSIVE")
(doseq [[k v] (take 45 (sort-by (comp - val) @deep))] (println v k))
(shutdown-agents)
(System/exit 0)
